#!/usr/bin/env python3
"""Generate docs/backlog.md from the review documents in docs/reviews/.

The reviews are the source of truth: each one carries an index table of findings with a Status
column, and optionally a `## Dependencies` section of edges between findings. This script derives
the aggregated backlog from both, so the backlog cannot drift from the reviews the way a
hand-maintained count does.

    python3 scripts/backlog.py            # rewrite docs/backlog.md
    python3 scripts/backlog.py --check    # exit 1 if the committed file is stale

Conventions are documented in docs/reviews/README.md.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
REVIEWS_DIR = REPO_ROOT / "docs" / "reviews"
BACKLOG_PATH = REPO_ROOT / "docs" / "backlog.md"

BANNER = "<!-- Generated by scripts/backlog.py. Do not edit by hand; run `python3 scripts/backlog.py`. -->"

SEVERITY_ORDER = {"High": 0, "Medium": 1, "Low": 2}

# An edge is unmet while its target is still open. `resolves` and `duplicates` point the other way:
# they say the *target* gets closed, so they never block the source.
BLOCKING_EDGES = {"needs"}
KNOWN_EDGES = {"needs", "resolves", "duplicates", "related"}

CELL_SPLIT = re.compile(r"(?<!\\)\|")
ID_IN_LINK = re.compile(r"\[([A-Z]+-\d+)\]")
QUALIFIED_ID = re.compile(r"^(\d{4}-\d{2}-\d{2})\s+([A-Z]+-\d+)$")
BARE_ID = re.compile(r"^([A-Z]+-\d+)$")


@dataclass
class Finding:
    review_date: str
    review_file: str
    fid: str
    title: str
    area: str
    severity: str
    verified: str
    status: str

    @property
    def qid(self) -> str:
        """Globally unique id. Both reviews define an AR-01, so the date is part of the name."""
        return f"{self.review_date} {self.fid}"

    @property
    def anchor(self) -> str:
        return f"reviews/{self.review_file}#{self.fid.lower()}"

    @property
    def state(self) -> str:
        head = self.status.split("(")[0].strip().lower()
        if head.startswith("done"):
            return "done"
        if head.startswith("won't fix") or head.startswith("wont fix"):
            return "wontfix"
        return "open"

    @property
    def severity_rank(self) -> int:
        return SEVERITY_ORDER.get(self.severity, len(SEVERITY_ORDER))


@dataclass
class Edge:
    source: str
    kind: str
    target: str
    note: str


@dataclass
class Review:
    date: str
    file: str
    title: str
    findings: list[Finding] = field(default_factory=list)
    edges: list[Edge] = field(default_factory=list)


def split_row(line: str) -> list[str]:
    cells = CELL_SPLIT.split(line.strip())
    if cells and not cells[0].strip():
        cells = cells[1:]
    if cells and not cells[-1].strip():
        cells = cells[:-1]
    return [c.strip().replace(r"\|", "|") for c in cells]


def is_separator(line: str) -> bool:
    return bool(re.fullmatch(r"\|[\s:|-]+\|", line.strip()))


def read_table(lines: list[str], start: int) -> tuple[list[list[str]], int]:
    """Read the body rows of a markdown table whose header is at `start`."""
    i = start + 1
    if i < len(lines) and is_separator(lines[i]):
        i += 1
    rows = []
    while i < len(lines) and lines[i].strip().startswith("|"):
        if not is_separator(lines[i]):
            rows.append(split_row(lines[i]))
        i += 1
    return rows, i


def parse_review(path: Path) -> Review | None:
    date_match = re.match(r"(\d{4}-\d{2}-\d{2})-", path.name)
    if not date_match:
        return None

    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()

    title = path.stem
    for line in lines:
        if line.startswith("# "):
            title = line[2:].strip()
            break

    review = Review(date=date_match.group(1), file=path.name, title=title)

    i = 0
    while i < len(lines):
        line = lines[i]
        if line.strip().startswith("|"):
            header = [c.lower() for c in split_row(line)]
            if "id" in header and "status" in header:
                rows, i = read_table(lines, i)
                review.findings.extend(parse_findings(review, header, rows, path))
                continue
            if "from" in header and "edge" in header and "to" in header:
                rows, i = read_table(lines, i)
                review.edges.extend(parse_edges(review, header, rows, path))
                continue
        i += 1

    return review


def parse_findings(review: Review, header: list[str], rows: list[list[str]], path: Path) -> list[Finding]:
    def col(name: str) -> int | None:
        return header.index(name) if name in header else None

    idx = {name: col(name) for name in ("id", "title", "area", "severity", "verified", "status")}
    out = []
    for row in rows:
        if idx["id"] is None or idx["id"] >= len(row):
            continue
        raw_id = row[idx["id"]]
        found = ID_IN_LINK.search(raw_id) or BARE_ID.match(raw_id)
        if not found:
            continue

        def cell(name: str) -> str:
            pos = idx[name]
            return row[pos] if pos is not None and pos < len(row) else ""

        out.append(
            Finding(
                review_date=review.date,
                review_file=review.file,
                fid=found.group(1),
                title=cell("title"),
                area=cell("area"),
                severity=cell("severity"),
                verified=cell("verified"),
                status=cell("status") or "Open",
            )
        )

    seen = set()
    for f in out:
        if f.fid in seen:
            fail(f"{path.name}: duplicate finding id {f.fid} in the index table")
        seen.add(f.fid)
    return out


def parse_edges(review: Review, header: list[str], rows: list[list[str]], path: Path) -> list[Edge]:
    i_from, i_edge, i_to = header.index("from"), header.index("edge"), header.index("to")
    i_note = header.index("note") if "note" in header else None
    out = []
    for row in rows:
        if max(i_from, i_edge, i_to) >= len(row):
            continue
        kind = row[i_edge].strip().strip("`").lower()
        if kind not in KNOWN_EDGES:
            fail(f"{path.name}: unknown edge kind '{kind}' (known: {', '.join(sorted(KNOWN_EDGES))})")
        note = row[i_note] if i_note is not None and i_note < len(row) else ""
        out.append(
            Edge(
                source=resolve_id(row[i_from], review, path),
                kind=kind,
                target=resolve_id(row[i_to], review, path),
                note=note,
            )
        )
    return out


def resolve_id(raw: str, review: Review, path: Path) -> str:
    """Resolve a reference to a globally unique id. A bare id belongs to the review it sits in."""
    value = raw.strip().strip("`")
    link = ID_IN_LINK.search(value)
    if link and not QUALIFIED_ID.match(value):
        value = link.group(1)
    qualified = QUALIFIED_ID.match(value)
    if qualified:
        return f"{qualified.group(1)} {qualified.group(2)}"
    bare = BARE_ID.match(value)
    if bare:
        return f"{review.date} {bare.group(1)}"
    fail(f"{path.name}: cannot parse finding reference '{raw}'")


def fail(message: str) -> None:
    print(f"error: {message}", file=sys.stderr)
    sys.exit(2)


def link(finding: Finding) -> str:
    return f"[{finding.qid}]({finding.anchor})"


def render(reviews: list[Review]) -> str:
    by_qid = {f.qid: f for r in reviews for f in r.findings}
    edges = [e for r in reviews for e in r.edges]

    for edge in edges:
        for ref in (edge.source, edge.target):
            if ref not in by_qid:
                fail(f"dependency references unknown finding '{ref}'")

    # A `resolves` or `duplicates` edge closes its target, so a shipped source closes the target too.
    effectively_done = set()
    for edge in edges:
        if edge.kind in ("resolves", "duplicates"):
            source = by_qid[edge.source]
            if source.state == "done":
                effectively_done.add(edge.target)

    def resolved(qid: str) -> bool:
        return by_qid[qid].state in ("done", "wontfix") or qid in effectively_done

    blockers: dict[str, list[Edge]] = {}
    for edge in edges:
        if edge.kind in BLOCKING_EDGES and not resolved(edge.target):
            blockers.setdefault(edge.source, []).append(edge)

    open_findings = [f for r in reviews for f in r.findings if f.state == "open" and f.qid not in effectively_done]
    ready = sorted(
        (f for f in open_findings if f.qid not in blockers),
        key=lambda f: (f.severity_rank, f.review_date, f.fid),
    )
    blocked = sorted(
        (f for f in open_findings if f.qid in blockers),
        key=lambda f: (f.severity_rank, f.review_date, f.fid),
    )

    out: list[str] = []
    w = out.append

    w("# Backlog")
    w("")
    w(BANNER)
    w("")
    w("Every open finding across all reviews, in one place. Derived from the index and `## Dependencies`")
    w("tables of [docs/reviews/](reviews/README.md) — the reviews stay the source of truth, this file is a")
    w("read-only view over them. Regenerate after changing any Status cell:")
    w("")
    w("```bash")
    w("python3 scripts/backlog.py")
    w("```")
    w("")
    w("A finding is **ready** when nothing it `needs` is still open, and **blocked** otherwise. Severity")
    w("orders within each group. The prose rationale for a given ordering stays in each review's")
    w("*Suggested order* section, which this file deliberately does not try to reproduce.")
    w("")

    w("## Summary")
    w("")
    w("| Review | Ready | Blocked | Done | Won't fix |")
    w("|---|---|---|---|---|")
    for review in reviews:
        counts = {"ready": 0, "blocked": 0, "done": 0, "wontfix": 0}
        for f in review.findings:
            if f.state == "done" or f.qid in effectively_done:
                counts["done"] += 1
            elif f.state == "wontfix":
                counts["wontfix"] += 1
            elif f.qid in blockers:
                counts["blocked"] += 1
            else:
                counts["ready"] += 1
        w(
            f"| [{review.title}](reviews/{review.file}) | {counts['ready']} | {counts['blocked']} "
            f"| {counts['done']} | {counts['wontfix']} |"
        )
    w(
        f"| **Total** | **{len(ready)}** | **{len(blocked)}** "
        f"| **{sum(1 for f in by_qid.values() if f.state == 'done' or f.qid in effectively_done)}** "
        f"| **{sum(1 for f in by_qid.values() if f.state == 'wontfix')}** |"
    )
    w("")

    w("## Ready now")
    w("")
    if ready:
        w("| Finding | Title | Area | Severity | Verified |")
        w("|---|---|---|---|---|")
        for f in ready:
            w(f"| {link(f)} | {f.title} | {f.area} | {f.severity} | {f.verified} |")
    else:
        w("Nothing ready. Every open finding is blocked, or there are none.")
    w("")

    w("## Blocked")
    w("")
    if blocked:
        w("| Finding | Title | Severity | Waiting on |")
        w("|---|---|---|---|")
        for f in blocked:
            waiting = ", ".join(
                f"{link(by_qid[e.target])}{f' — {e.note}' if e.note else ''}" for e in blockers[f.qid]
            )
            w(f"| {link(f)} | {f.title} | {f.severity} | {waiting} |")
    else:
        w("Nothing is blocked.")
    w("")

    other_edges = [e for e in edges if e.kind not in BLOCKING_EDGES]
    if other_edges:
        w("## Other relationships")
        w("")
        w("| From | Edge | To | Note |")
        w("|---|---|---|---|")
        for e in sorted(other_edges, key=lambda e: (e.kind, e.source)):
            w(f"| {link(by_qid[e.source])} | `{e.kind}` | {link(by_qid[e.target])} | {e.note} |")
        w("")

    closed = sorted(
        (f for f in by_qid.values() if f.state in ("done", "wontfix") or f.qid in effectively_done),
        key=lambda f: (f.review_date, f.fid),
    )
    w("## Closed")
    w("")
    if closed:
        w("| Finding | Title | Status |")
        w("|---|---|---|")
        for f in closed:
            status = f.status
            if f.state == "open" and f.qid in effectively_done:
                closer = next(
                    e.source for e in edges if e.target == f.qid and e.kind in ("resolves", "duplicates")
                )
                status = f"Closed by {by_qid[closer].fid} — {by_qid[closer].status}"
            w(f"| {link(f)} | {f.title} | {status} |")
    else:
        w("Nothing closed yet.")
    w("")

    w("---")
    w("")
    w("Observations not yet filed as findings are listed under *Unfiled observations* in")
    w("[reviews/README.md](reviews/README.md). Turning a finding into work is described in")
    w("[changes/README.md](changes/README.md).")

    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if docs/backlog.md does not match the reviews, without writing",
    )
    args = parser.parse_args()

    paths = sorted(p for p in REVIEWS_DIR.glob("*.md") if p.name != "README.md")
    reviews = [r for r in (parse_review(p) for p in paths) if r is not None]
    if not reviews:
        fail(f"no review documents found in {REVIEWS_DIR}")

    rendered = render(reviews)

    if args.check:
        current = BACKLOG_PATH.read_text(encoding="utf-8") if BACKLOG_PATH.exists() else ""
        if current != rendered:
            print(
                "error: docs/backlog.md is stale. Run `python3 scripts/backlog.py` and commit the result.",
                file=sys.stderr,
            )
            return 1
        print(f"docs/backlog.md is up to date ({len(reviews)} reviews).")
        return 0

    BACKLOG_PATH.write_text(rendered, encoding="utf-8")
    print(f"wrote {BACKLOG_PATH.relative_to(REPO_ROOT)} from {len(reviews)} reviews.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
